# Получаем четырехзначное число через input()
number = input("Введите четырехзначное число: ")

# Проверяем, что число действительно четырехзначное
if len(number) == 4 and number.isdigit():
    # Разбиваем число на цифры
    first = number[0]   # первая цифра
    second = number[1]  # вторая цифра
    third = number[2]   # третья цифра
    fourth = number[3]  # четвертая цифра

    # Проверяем: первая == четвертая И вторая == третья
    if first == fourth and second == third:
        print("Высказывание истинно: число читается одинаково в обоих направлениях")
    else:
        print("Высказывание ложно: число не является палиндромом")
else:
    print("Ошибка: нужно ввести именно четырехзначное число!")