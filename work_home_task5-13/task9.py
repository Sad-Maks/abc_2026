# Получаем коэффициенты A и B через input()
A = float(input("Введите коэффициент A (A ≠ 0): "))
B = float(input("Введите коэффициент B: "))

# Проверяем, что A не равен нулю
if A != 0:
    # Решаем уравнение: A·x + B = 0  =>  x = -B / A
    x = -B / A
    print(f"Корень уравнения: x = {x}")
else:
    print("Ошибка: коэффициент A не должен быть равен нулю!")