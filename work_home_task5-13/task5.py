# Считываем два числа с клавиатуры
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))

# Выполняем операции
summ = a + b                # Сумма
diff = a - b                # Разность
quot = a / b                # Частное
prod = a * b                # Произведение
int_div = a // b            # Целочисленное деление
mod = a % b                 # Остаток от деления
power = a ** b              # Возведение в степень

# Выводим результаты
print(f"Сумма: {summ}")
print(f"Разность: {diff}")
print(f"Частное: {quot}")
print(f"Произведение: {prod}")
print(f"Целочисленное деление: {int_div}")
print(f"Остаток от деления: {mod}")
print(f"Возведение в степень: {power}")


