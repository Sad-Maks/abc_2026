# Получаем номер года через input()
year = int(input("Введите год: "))

# Определяем смещение относительно 1984 года (начало цикла — зелёная крыса)
# Используем остаток от деления, чтобы учесть годы до 1984
offset = (year - 1984) % 60

# Названия животных 
animals = [
    "Крыса", "Бык", "Тигр", "Заяц",
    "Дракон", "Змея", "Лошадь", "Овца",
    "Обезьяна", "Петух", "Собака", "Свинья"
]

# Названия цветов 
colors = ["Зелёный", "Красный", "Жёлтый", "Белый", "Чёрный"]

# Определяем животное: каждые 12 лет цикл повторяется
animal = animals[offset % 12]

# Определяем цвет: каждые 12 лет меняется животное,
# а каждые 2 года — цвет 
# offset // 2 даёт индекс цвета от 0 до 29, делим по модулю 5
color = colors[(offset // 2) % 5]

# Выводим результат
print(f"{year} год — год {color.lower()} {animal.lower()}")